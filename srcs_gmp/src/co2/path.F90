!
   function path(a,b,c,e)                                   
!-------------------------------------------------------------------------------
!....                                                                           
!     double precision xa,ca                                                    
!
!-------------------------------------------------------------------------------
   use comco2, only : xa, ca, eta, sexpv, core, uexp, sexp
!-------------------------------------------------------------------------------
   pexp=1./sexp                                                              
   path=((a-b)**pexp*(a+b+c))/(e*(a+b+c)+(a-b)**(pexp-1.))          
!
   return                                                                    
   end                                                                       
!-------------------------------------------------------------------------------
